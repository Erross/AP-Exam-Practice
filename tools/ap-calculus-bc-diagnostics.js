const { AP_SUBJECTS } = require('../js/subjects');
const { loadEffectiveBank } = require('./subject-release-audit');
const subject = AP_SUBJECTS.find((s) => s.id === 'ap-calculus-bc');
const { bank } = loadEffectiveBank(subject);
const abs = /\b(always|never|every|only|entirely|unlimited|impossible|guaranteed)\b/i;
const wc = (s) => String(s||'').trim().split(/\s+/).filter(Boolean).length;
const short = bank.filter((q) => String(q.e||'').trim().length < 90).map((q) => [q.id, q.topicCode, String(q.e||'').length, q.e]);
const absolutes = bank.filter((q) => q.o.filter((_,i) => i !== q.c[0]).filter((o) => abs.test(o)).length > 1).map((q) => [q.id,q.topicCode,q.o]);
const uniqueLongest = bank.filter((q) => { const lens=q.o.map(wc); const m=Math.max(...lens); return lens[q.c[0]]===m && lens.filter(x=>x===m).length===1; }).map((q) => [q.id,q.topicCode,q.o.map(wc),q.o[q.c[0]]]);
console.log(JSON.stringify({ bankSize:bank.length, short, absolutes, uniqueLongestCount:uniqueLongest.length, uniqueLongest }, null, 2));
